"""Build design/tokens.css from the DTCG token sources.

Tier 1 primitives + tier 2 semantic (shared + per-mode) -> CSS custom properties.
Dark is the default mode on :root (docs/03 is dark-first); [data-theme="light"]
overrides only the semantic colour/shadow layer. Components (Stage 3+) consume
semantic vars exclusively.

Run:  backend/.venv/bin/python design/build_tokens.py
"""

from __future__ import annotations

import json
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
TOKENS = HERE / "tokens"
OUT = HERE / "tokens.css"

FONTS = [
    ("Inter", 400, "inter-latin-400-normal.woff2"),
    ("Inter", 500, "inter-latin-500-normal.woff2"),
    ("Inter", 600, "inter-latin-600-normal.woff2"),
    ("Inter", 700, "inter-latin-700-normal.woff2"),
    ("JetBrains Mono", 400, "jetbrains-mono-latin-400-normal.woff2"),
    ("JetBrains Mono", 500, "jetbrains-mono-latin-500-normal.woff2"),
    ("JetBrains Mono", 600, "jetbrains-mono-latin-600-normal.woff2"),
    ("JetBrains Mono", 700, "jetbrains-mono-latin-700-normal.woff2"),
]


def load(name: str) -> dict:
    return json.loads((TOKENS / name).read_text())


def is_leaf(node: dict) -> bool:
    return isinstance(node, dict) and "$value" in node


def walk(node: dict, path: tuple[str, ...] = ()):
    for key, val in node.items():
        if key.startswith("$"):
            continue
        if is_leaf(val):
            yield path + (key,), val
        elif isinstance(val, dict):
            yield from walk(val, path + (key,))


def _kebab(dotted: str) -> str:
    return re.sub(r"([A-Z])", r"-\1", dotted).lower()


def var_name(path: tuple[str, ...]) -> str:
    return "--" + "-".join(_kebab(seg) for seg in path)


def css_value(leaf: dict) -> str:
    v = leaf["$value"]
    t = leaf.get("$type")
    if isinstance(v, str) and v.startswith("{") and v.endswith("}"):
        return f"var(--{_kebab(v[1:-1]).replace('.', '-')})"
    if t == "typography":
        raise ValueError("composite typography tokens are expanded by the caller")
    if t == "shadow":
        return f"{v['offsetX']} {v['offsetY']} {v['blur']} {v['spread']} {v['color']}"
    if isinstance(v, float) and t == "number":
        return str(v)
    return str(v)


def emit(group: dict, indent: str = "  ") -> list[str]:
    lines: list[str] = []
    for path, leaf in walk(group):
        if leaf.get("$type") == "typography":
            for field, fv in leaf["$value"].items():
                fk = re.sub(r"([A-Z])", r"-\1", field).lower()
                val = f"var(--{_kebab(fv[1:-1]).replace('.', '-')})" if isinstance(fv, str) and fv.startswith("{") else str(fv)
                lines.append(f"{indent}{var_name(path)}-{fk}: {val};")
        else:
            lines.append(f"{indent}{var_name(path)}: {css_value(leaf)};")
    return lines


def font_faces() -> str:
    out = []
    for family, weight, file in FONTS:
        out.append(
            "@font-face {\n"
            f"  font-family: '{family}';\n"
            "  font-style: normal;\n"
            f"  font-weight: {weight};\n"
            "  font-display: swap;\n"
            f"  src: url('fonts/{file}') format('woff2');\n"
            "}"
        )
    return "\n".join(out)


def main() -> str:
    prim = load("primitives.json")
    shared = load("semantic.shared.json")
    dark = load("semantic.dark.json")
    light = load("semantic.light.json")

    head = (
        "/* NEXUS-AI design tokens — generated by design/build_tokens.py. DO NOT EDIT.\n"
        "   Sources: design/tokens/*.json (W3C DTCG 2025.10). Tier 1 primitives,\n"
        "   tier 2 semantic; dark = default mode, light = [data-theme=light] override.\n"
        "   Components must reference semantic vars only (docs/09 §3). */\n"
    )
    blocks = [head, font_faces(), "", ":root {"]
    blocks += emit(prim)
    blocks += emit(shared)
    blocks += emit(dark)
    blocks += ["}", "", "[data-theme='light'] {"]
    blocks += emit(light)
    blocks += ["}", ""]
    css = "\n".join(blocks)
    OUT.write_text(css)
    return css


if __name__ == "__main__":
    css = main()
    print(f"wrote {OUT} ({len(css)} bytes, {css.count(chr(10))} lines)")
